 // 1. НАСТРОЙКА ПЕРЕМЕННЫХ И ПОИСК ЭЛЕМЕНТОВ 

// контейнер слайдера на странице
const slider = document.querySelector('.slider');

// кнопки "Предыдущий" и "Следующий"
const prevButton = document.querySelector('.prev-button');
const nextButton = document.querySelector('.next-button');

// Массив всех изображений в слайдере
const slides = Array.from(slider.querySelectorAll('img'));

// общее количество слайдов
const slideCount = slides.length;

// Отслеживания текущего слайда
let slideIndex = 0;

 
// 2. ОБРАБОТЧИКИ СОБЫТИЙ ДЛЯ КНОПОК 

prevButton.addEventListener('click', showPreviousSlide);
nextButton.addEventListener('click', showNextSlide);


// 3. ФУНКЦИИ ПЕРЕКЛЮЧЕНИЯ СЛАЙДОВ 

// предыдущий слайд
function showPreviousSlide() {
    slideIndex = (slideIndex - 1 + slideCount) % slideCount; // зацикливание слайдов
    updateSlider();
    updateDots();
}

// Показать следующий слайд
function showNextSlide() {
    slideIndex = (slideIndex + 1) % slideCount;
    updateSlider();
}

// 4. ФУНКЦИЯ ОБНОВЛЕНИЯ ОТОБРАЖЕНИЯ СЛАЙДЕРА

function updateSlider() {
    // Перебираем все слайды
    slides.forEach((slide, index) => {
        if (index === slideIndex) {
            slide.style.display = 'block';
        } else {
            slide.style.display = 'none';
        }
    });
}

// Запуск слайдера при загрузке страницы 
updateSlider();

