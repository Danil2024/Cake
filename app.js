// Функция открытия изображения на весь экран
function openFullscreenImage(element) {
    // контейнер для полноэкранного просмотра
    const fullscreenContainer = document.getElementById('fullscreen-container');
    // изображение внутри контейнера
    const fullscreenImage = document.getElementById('fullscreen-image');

    // путь к изображению, на которое кликнули
    fullscreenImage.src = element.src;

    // Показываем контейнер 
    fullscreenContainer.style.display = 'flex';
}

// Закрытие полноэкранного просмотра
function closeFullscreenImage() {
    const fullscreenContainer = document.getElementById('fullscreen-container');
    fullscreenContainer.style.display = 'none';
}

// 6. КНОПКА "НАВЕРХ" И ПЛАВНАЯ ПРОКРУТКА  

// Отслеживание прокрутки страницы
window.onscroll = function() {
    scrollFunction();
};

// Функция показа/скрытия кнопки "Наверх"
function scrollFunction() {
    if (document.body.scrollTop > 20 || document.documentElement.scrollTop > 20) {
        document.getElementById('scrollToTopButton').style.display = 'block';
    } else {
        document.getElementById('scrollToTopButton').style.display = 'none';
    }
}

// При клике на кнопку "Наверх" — плавная прокрутка
document.getElementById('scrollToTopButton').addEventListener('click', function() {
    scrollToTop();
});

// Плавная прокрутка наверх
function scrollToTop() {
    // Чем выше страница, тем быстрее прокрутка
    const scrollStep = -window.scrollY / 15;
    
    // Плавное прокручивание страницы
    const scrollInterval = setInterval(function() {
        if (window.scrollY !== 0) {
            // Если не достигли верха — прокручиваем на шаг
            window.scrollBy(0, scrollStep);
        } else {
            // Если достигли верха — останавливаем интервал
            clearInterval(scrollInterval);
        }
    }, 15);
}

